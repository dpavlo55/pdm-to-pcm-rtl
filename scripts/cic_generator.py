def generate_model_hpp(params: CicParams) -> str:
    """Return the full text of cic_model.hpp for the given CicParams.

    The generated header contains two things:

    1. ``CicModel`` — a header-only C++ class using ``int64_t`` with
       explicit wrap arithmetic.  Bit-accurate with ``cic.sv``.
       No external dependencies beyond ``<cstdint>`` and ``<cstring>``.

    2. ``cic_model_sc`` — an ``SC_MODULE`` wrapper compiled only when
       ``__SYSTEMC__`` is defined (i.e. when including ``<systemc.h>``
       beforehand, or when compiled with ``sccom``).
    """
    N = params.N
    R = params.R
    M = params.M
    Bin = params.Bin
    Bout = params.Bout

    integ_stages: List[StageParams] = params.stages[:N]
    comb_stages:  List[StageParams] = params.stages[N:]

    integ_widths = [s.width for s in integ_stages]
    comb_widths  = [s.width for s in comb_stages]
    last_comb_w  = comb_widths[-1]
    output_drop  = last_comb_w - Bout

    iw_arr = "{" + ", ".join(str(w) for w in integ_widths) + "}"
    cw_arr = "{" + ", ".join(str(w) for w in comb_widths) + "}"
    m_dim  = max(M, 1)  # array dimension (C++ forbids zero-size arrays)

    L: List[str] = []

    # -------------------------------------------------------------------------
    # File header
    # -------------------------------------------------------------------------
    L += [
        "// Auto-generated by cic_generator.py — DO NOT EDIT BY HAND",
        f"// CIC fixed-point reference model (C++): N={N}, R={R}, M={M}, Bin={Bin}, Bout={Bout}",
        f"// Stage widths (integrators): {integ_widths}",
        f"// Stage widths (comb):        {comb_widths}",
        f"// Max accumulator width: {params.max_width}  |  Output bit-select drops {output_drop} LSBs",
        "//",
        "// Bit-accurate with cic.sv (PIPELINE_ENABLE=0). No external dependencies.",
        "// When compiled with <systemc.h> already included, also provides",
        "// cic_model_sc — an SC_MODULE wrapper for SystemC co-simulation.",
        "",
        "#pragma once",
        "#include <cstdint>",
        "#include <cstring>",
        "",
    ]

    # -------------------------------------------------------------------------
    # CicModel class
    # -------------------------------------------------------------------------
    L += [
        "// ---------------------------------------------------------------------------",
        "// CicModel — bit-accurate CIC decimation filter (C++, no dependencies)",
        "//",
        "//   step(pdm_in, &pcm_out) — call once per PDM sample.",
        "//     Returns 1 and sets *pcm_out every R calls; returns 0 otherwise.",
        "//   reset() — zeros all internal state.",
        "// ---------------------------------------------------------------------------",
        "class CicModel {",
        "public:",
        f"    enum : int {{ N = {N}, R = {R}, M = {M}, Bin = {Bin}, Bout = {Bout},"
        f" OUTPUT_DROP = {output_drop} }};",
        "",
        "    CicModel() { reset(); }",
        "",
        "    void reset() {",
        "        memset(_integ,    0, sizeof(_integ));",
        "        memset(_comb_dly, 0, sizeof(_comb_dly));",
        "        _dec_cnt = 0;",
        "    }",
        "",
        "    // Returns 1 if a new PCM sample is ready (sets *pcm_out), 0 otherwise.",
        "    int step(int pdm_in, int *pcm_out) {",
        f"        static constexpr int IW[{N}] = {iw_arr};  // integrator stage widths",
        f"        static constexpr int CW[{N}] = {cw_arr};  // comb stage widths",
        "",
        "        // --- Integrators: compute all feeds first, then update simultaneously ---",
        "        // Matches SV always_ff: all RHS are evaluated from pre-clock-edge values.",
        f"        int64_t feed[{N}];",
        "        feed[0] = pdm_in ? INT64_C(1) : INT64_C(-1);",
        f"        for (int i = 1; i < N; ++i)",
        f"            feed[i] = _top_bits(_integ[i-1], IW[i-1], IW[i]);",
        "        const int64_t last_integ_pre = _integ[N-1];",
        f"        for (int i = 0; i < N; ++i)",
        "            _integ[i] = _wrap(_integ[i] + feed[i], IW[i]);",
        "",
        "        // --- Decimation counter ---",
        "        const bool dec_en = (_dec_cnt == R - 1);",
        "        _dec_cnt = dec_en ? 0 : _dec_cnt + 1;",
        "        if (!dec_en) return 0;",
        "",
        "        // --- Comb stages (run every R-th sample) ---",
        "        // Use pre-update last integrator: RTL comb reads integ before the clock edge.",
        "        int64_t comb_val = last_integ_pre;",
        "        for (int i = 0; i < N; ++i) {",
        "            const int    prev_w = (i == 0) ? IW[N-1] : CW[i-1];",
        "            const int64_t feed  = _top_bits(comb_val, prev_w, CW[i]);",
        "            const int64_t dly   = _comb_dly[i][M-1];",
        "            for (int m = M-1; m > 0; --m) _comb_dly[i][m] = _comb_dly[i][m-1];",
        "            _comb_dly[i][0] = feed;",
        "            comb_val = _wrap(feed - dly, CW[i]);",
        "        }",
        "",
        "        // --- Output: top Bout bits of final comb stage ---",
        f"        *pcm_out = (int)_top_bits(comb_val, CW[N-1], {Bout});",
        "        return 1;",
        "    }",
        "",
        "private:",
        f"    int64_t _integ[{N}];",
        f"    int64_t _comb_dly[{N}][{m_dim}];",
        "    int     _dec_cnt;",
        "",
        "    // Wrap v to w signed bits — equivalent to SV register truncation.",
        "    static inline int64_t _wrap(int64_t v, int w) {",
        "        if (w <= 0 || w >= 64) return v;",
        "        const int64_t mask = (INT64_C(1) << w) - 1;",
        "        v &= mask;",
        "        if ((v >> (w - 1)) & 1) v |= ~mask;  // sign-extend",
        "        return v;",
        "    }",
        "",
        "    // Extract top `to` bits from a `from`-bit signed value.",
        "    // Equivalent to SV bit-select v[from-1 : from-to].",
        "    static inline int64_t _top_bits(int64_t v, int from, int to) {",
        "        v = _wrap(v, from);",
        "        if (from > to) v >>= (from - to);  // arithmetic right shift",
        "        return _wrap(v, to);",
        "    }",
        "};",
        "",
    ]

    # -------------------------------------------------------------------------
    # SC_MODULE wrapper
    # -------------------------------------------------------------------------
    L += [
        "// ---------------------------------------------------------------------------",
        "// cic_model_sc — SC_MODULE wrapper for SystemC co-simulation",
        "//",
        "// Only compiled when <systemc.h> has been included before this header",
        "// (i.e. __SYSTEMC__ is defined by the SystemC library headers).",
        "//",
        "// Interface matches cic.sv:",
        "//   clk, rst_n, pdm_in, pdm_in_valid  ->  pcm_out, pcm_out_valid",
        "// ---------------------------------------------------------------------------",
        "#ifdef __SYSTEMC__",
        "",
        "SC_MODULE(cic_model_sc) {",
        "    sc_in<bool>            clk;",
        "    sc_in<bool>            rst_n;",
        "    sc_in<bool>            pdm_in;",
        "    sc_in<bool>            pdm_in_valid;",
        f"    sc_out<sc_int<{Bout}>> pcm_out;",
        "    sc_out<bool>           pcm_out_valid;",
        "",
        "    SC_CTOR(cic_model_sc) {",
        "        SC_CTHREAD(run, clk.pos());",
        "        async_reset_signal_is(rst_n, false);",
        "    }",
        "",
        "    // SC_CTHREAD body — reset block runs while rst_n is low.",
        "    void run() {",
        "        pcm_out.write(0);",
        "        pcm_out_valid.write(false);",
        "        _model.reset();",
        "        wait();  // first rising edge after de-assertion",
        "        while (true) {",
        "            int  pcm_val = 0;",
        "            int  valid   = 0;",
        "            if (pdm_in_valid.read())",
        "                valid = _model.step(pdm_in.read() ? 1 : 0, &pcm_val);",
        "            pcm_out_valid.write(valid != 0);",
        "            if (valid) pcm_out.write(pcm_val);",
        "            wait();",
        "        }",
        "    }",
        "",
        "private:",
        "    CicModel _model;",
        "};",
        "",
        "#endif  // __SYSTEMC__",
        "",
    ]

    return "\n".join(L)


# ---------------------------------------------------------------------------
# File writing
# ---------------------------------------------------------------------------

def write_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"Written: {path}")


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> None:
    script_dir = Path(__file__).parent
    default_outdir = str(script_dir / ".." / "src")
    default_tbdir  = str(script_dir / ".." / "tb")

    parser = argparse.ArgumentParser(
        description="Generate a bit-accurate CIC decimation filter (cic.sv) from Hogenauer pruning parameters."
    )
    parser.add_argument("--N",      type=int, default=3,  help="Filter order (default: 3)")
    parser.add_argument("--R",      type=int, default=8,  help="Decimation ratio (default: 8)")
    parser.add_argument("--M",      type=int, default=1,  help="Differential delay (default: 1)")
    parser.add_argument("--Bin",    type=int, default=1,  help="Input bit width (default: 1)")
    parser.add_argument("--Bout",   type=int, default=8,  help="Output bit width (default: 8)")
    parser.add_argument("--outdir", default=default_outdir, help="Output directory for cic.sv (default: ../src)")
    parser.add_argument("--tbdir",  default=default_tbdir,  help="Output directory for cic_model.py when --tb is set (default: ../tb)")
    parser.add_argument(
        "--tb",
        action="store_true",
        default=False,
        help="Also generate cic_model.py: a bit-accurate fpbinary fixed-point reference model (requires fpbinary).",
    )
    args = parser.parse_args(argv)

    params = compute_cic_params(
        N=args.N, R=args.R, M=args.M, Bin=args.Bin, Bout=args.Bout
    )

    calculate_cic_pruning(N=args.N, R=args.R, M=args.M, Bin=args.Bin, Bout=args.Bout)

    sv_content = generate_sv(params)
    outdir = Path(os.path.realpath(args.outdir))
    write_file(outdir / "cic.sv", sv_content)
    if args.tb:
        tbdir = Path(os.path.realpath(args.tbdir))
        write_file(tbdir / "cic_model.py",  generate_model_py(params))
        write_file(tbdir / "cic_model.hpp", generate_model_hpp(params))


if __name__ == "__main__":
    main()
