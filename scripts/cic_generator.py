def generate_model_py(params: CicParams) -> str:
    """Return the full text of cic_model.py for the given CicParams.

    The generated module contains a single ``CicModel`` class whose
    :meth:`step` method processes one PDM bit at a time using
    ``fpbinary.FpBinary`` with the same Hogenauer-pruned per-stage widths
    and wrap-on-overflow behaviour as ``cic.sv``.
    """
    N = params.N
    R = params.R
    M = params.M
    Bin = params.Bin
    Bout = params.Bout

    integ_stages: List[StageParams] = params.stages[:N]
    comb_stages:  List[StageParams] = params.stages[N:]

    integ_widths = [s.width for s in integ_stages]
    comb_widths  = [s.width for s in comb_stages]

    last_comb_w = comb_widths[-1]
    output_drop = last_comb_w - Bout  # LSBs dropped in output bit-select

    L: List[str] = []

    # -------------------------------------------------------------------------
    # Header
    # -------------------------------------------------------------------------
    L += [
        "# Auto-generated by cic_generator.py — DO NOT EDIT BY HAND",
        f"# CIC fixed-point reference model: N={N}, R={R}, M={M}, Bin={Bin}, Bout={Bout}",
        f"# Stage widths (integrators): {integ_widths}",
        f"# Stage widths (comb):        {comb_widths}",
        f"# Max accumulator width: {params.max_width}  |  Output bit-select drops {output_drop} LSBs",
        "#",
        "# Bit-accurate with cic.sv (PIPELINE_ENABLE=0).",
        "# Requires: fpbinary  (pip install fpbinary)",
        "",
        "from __future__ import annotations",
        "",
        "from collections import deque",
        "",
        "from fpbinary import FpBinary, OverflowEnum, RoundingEnum",
        "",
    ]

    # -------------------------------------------------------------------------
    # Module-level helpers
    # -------------------------------------------------------------------------
    L += [
        "# ---------------------------------------------------------------------------",
        "# Helpers",
        "# ---------------------------------------------------------------------------",
        "",
        "_WRAP  = OverflowEnum.wrap",
        "_FLOOR = RoundingEnum.direct_neg_inf",
        "",
        "",
        "def _fp(int_bits: int, value: float = 0.0) -> FpBinary:",
        '    """Signed fixed-point integer: ``int_bits`` wide, no fractional part."""',
        "    return FpBinary(int_bits=int_bits, frac_bits=0, signed=True, value=value)",
        "",
        "",
        "def _clip(fp: FpBinary, int_bits: int) -> FpBinary:",
        '    """Resize ``fp`` in-place to ``int_bits`` bits, wrapping on overflow (= SV register truncation)."""',
        "    fp.resize((int_bits, 0), overflow_mode=_WRAP, round_mode=_FLOOR)",
        "    return fp",
        "",
        "",
        "def _top_bits(value: float, from_bits: int, to_bits: int) -> FpBinary:",
        '    """Extract the top ``to_bits`` of a ``from_bits``-wide signed integer value.',
        "",
        "    Equivalent to the SV bit-select ``v[from_bits-1 : from_bits-to_bits]``.",
        '    """',
        "    fp = _fp(from_bits, value)",
        "    if from_bits == to_bits:",
        "        return fp",
        "    fp.resize((from_bits, -(from_bits - to_bits)), overflow_mode=_WRAP, round_mode=_FLOOR)",
        "    return _fp(to_bits, float(fp.bits_to_signed()))",
        "",
        "",
    ]

    # -------------------------------------------------------------------------
    # CicModel class
    # -------------------------------------------------------------------------
    L += [
        "# ---------------------------------------------------------------------------",
        "# CicModel",
        "# ---------------------------------------------------------------------------",
        "",
        "",
        "class CicModel:",
        '    """Bit-accurate CIC decimation filter reference model.',
        "",
        f"    Parameters baked in: N={N}, R={R}, M={M}, Bin={Bin}, Bout={Bout}.",
        "",
        "    Call :meth:`step` once per PDM input sample.  Returns ``(output, valid)``",
        "    where *output* is a signed integer in the ``Bout``-bit range and *valid*",
        "    is ``True`` once every ``R`` input samples.",
        '    """',
        "",
        f"    N    = {N}",
        f"    R    = {R}",
        f"    M    = {M}",
        f"    Bin  = {Bin}",
        f"    Bout = {Bout}",
        "",
        f"    INTEG_WIDTHS: list[int] = {integ_widths!r}",
        f"    COMB_WIDTHS:  list[int] = {comb_widths!r}",
        f"    OUTPUT_DROP = {output_drop}  # LSBs dropped in output bit-select (last_comb_w - Bout)",
        "",
        "    def __init__(self) -> None:",
        "        self.reset()",
        "",
        "    def reset(self) -> None:",
        '        """Reset all internal state to zero."""',
        "        self._integ: list[FpBinary] = [_fp(w) for w in self.INTEG_WIDTHS]",
        "        self._comb_dly: list[deque] = [",
        "            deque([_fp(w) for _ in range(self.M)], maxlen=self.M)",
        "            for w in self.COMB_WIDTHS",
        "        ]",
        "        self._dec_cnt: int = 0",
        "",
        "    def step(self, pdm_in: int) -> tuple[int | None, bool]:",
        '        """Process one PDM input sample.',
        "",
        "        Args:",
        "            pdm_in: 0 or 1.",
        "",
        "        Returns:",
        "            ``(output, valid)`` — *output* is ``None`` when not valid.",
        '        """',
        "        # --- Integrators (run every sample) ----------------------------",
        "        # PDM bipolar mapping: 1 -> +1, 0 -> -1",
        "        pdm_val = 1.0 if pdm_in else -1.0",
        "",
        "        # Compute all feeds from current (pre-update) state first, then update.",
        "        # This matches SV always_ff semantics: all RHS read pre-clock-edge values.",
        "        feeds = []",
        "        for i, w in enumerate(self.INTEG_WIDTHS):",
        "            if i == 0:",
        "                feeds.append(_fp(self.INTEG_WIDTHS[0], pdm_val))",
        "            else:",
        "                prev_w = self.INTEG_WIDTHS[i - 1]",
        "                feeds.append(_top_bits(float(self._integ[i - 1]), prev_w, w))",
        "        last_integ_pre = _fp(self.INTEG_WIDTHS[-1], float(self._integ[-1]))",
        "        for i, w in enumerate(self.INTEG_WIDTHS):",
        "            self._integ[i] = _clip(self._integ[i] + feeds[i], w)",
        "",
        "        # --- Decimation counter ----------------------------------------",
        "        dec_en = (self._dec_cnt == self.R - 1)",
        "        if dec_en:",
        "            self._dec_cnt = 0",
        "        else:",
        "            self._dec_cnt += 1",
        "",
        "        if not dec_en:",
        "            return None, False",
        "",
        "        # --- Comb stages (run every R-th sample) -----------------------",
        "        # Use pre-update last integrator value: RTL comb reads integ before clock edge.",
        "        comb_feed: FpBinary = last_integ_pre",
        "",
        "        for i, w in enumerate(self.COMB_WIDTHS):",
        "            prev_w = self.INTEG_WIDTHS[-1] if i == 0 else self.COMB_WIDTHS[i - 1]",
        "            feed = _top_bits(float(comb_feed), prev_w, w)",
        "            dly_out: FpBinary = self._comb_dly[i][-1]  # M-step delayed value",
        "            self._comb_dly[i].appendleft(_fp(w, float(feed)))",
        "            diff = feed - dly_out",
        "            comb_feed = _clip(diff, w)",
        "",
        "        # --- Output bit-select -----------------------------------------",
        "        out = _fp(self.COMB_WIDTHS[-1], float(comb_feed))",
        "        if self.OUTPUT_DROP > 0:",
        "            out.resize(",
        "                (self.COMB_WIDTHS[-1], -self.OUTPUT_DROP),",
        "                overflow_mode=_WRAP,",
        "                round_mode=_FLOOR,",
        "            )",
        "        return int(out.bits_to_signed()), True",
        "",
        "",
    ]

    # -------------------------------------------------------------------------
    # __main__ block
    # -------------------------------------------------------------------------
    L += [
        'if __name__ == "__main__":',
        "    import sys",
        "",
        "    model = CicModel()",
        "    pdm_seq = [int(b) for b in (sys.argv[1] if len(sys.argv) > 1 else \"10110011\")]",
        f"    print(\"CicModel(N={N}, R={R}, M={M}, Bin={Bin}, Bout={Bout})\")",
        "    for pdm in pdm_seq:",
        "        out, valid = model.step(pdm)",
        "        if valid:",
        "            print(f\"  -> output = {out}\")",
        "",
    ]

    return "\n".join(L)


