"""
cic_generator.py — Generate a bit-accurate CIC decimation filter in SystemVerilog.

Computes Hogenauer-pruned per-stage widths from cic_pruning.py, then emits
a fully unrolled cic.sv with concrete bit-widths baked in per stage.

The generated module has a single bit parameter PIPELINE_ENABLE (default 0):
  - 0: combinational comb chain (all N diffs in one always_comb; only M-deep
       delay registers are always_ff gated by dec_en).
  - 1: each comb difference output is registered (always_ff, gated by dec_en),
       adding N decimation-cycle latency but giving cleaner timing closure.

Usage:
  python cic_generator.py [--N 3] [--R 8] [--M 1] [--Bin 1] [--Bout 8]
                          [--outdir ../src]

When run without arguments defaults to the PDM-to-PCM scenario:
  N=3, R=8, M=1, Bin=1, Bout=8  ->  rtl/src/cic.sv
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import List

# Allow running from any working directory
sys.path.insert(0, str(Path(__file__).parent))

from cic_pruning import CicParams, StageParams, calculate_cic_pruning, compute_cic_params


# ---------------------------------------------------------------------------
# SV generation
# ---------------------------------------------------------------------------

def _w(width: int) -> str:
    """Return a SystemVerilog width prefix, e.g. '[9:0]' or '[0:0]' for 1-bit."""
    return f"[{width - 1}:0]"


def generate_sv(params: CicParams) -> str:
    """Return the full text of cic.sv for the given CicParams."""
    N = params.N
    R = params.R
    M = params.M
    Bin = params.Bin
    Bout = params.Bout
    max_width = params.max_width
    trunc_bits = params.trunc_bits

    # Integrator stages:  index 1..N   -> params.stages[0..N-1]
    # Comb stages:        index N+1..2N -> params.stages[N..2N-1]
    integ_stages: List[StageParams] = params.stages[:N]
    comb_stages:  List[StageParams] = params.stages[N:]

    # Counter width: enough bits to hold R-1
    import math
    cnt_bits = max(1, math.ceil(math.log2(R))) if R > 1 else 1

    L: List[str] = []

    # -------------------------------------------------------------------------
    # Header comment
    # -------------------------------------------------------------------------
    L += [
        "// Auto-generated by cic_generator.py — DO NOT EDIT BY HAND",
        f"// CIC decimation filter: N={N}, R={R}, M={M}, Bin={Bin}, Bout={Bout}",
        f"// Max accumulator width: {max_width} bits  |  Output truncation: {trunc_bits} bits",
        "//",
        "// PIPELINE_ENABLE=0 (default): combinational comb chain",
        "// PIPELINE_ENABLE=1          : each comb stage individually registered",
        "",
    ]

    # -------------------------------------------------------------------------
    # Module declaration
    # -------------------------------------------------------------------------
    integ0_w = integ_stages[0].width
    L += [
        "module cic",
        "    #(",
        "        parameter bit PIPELINE_ENABLE = 1'b0",
        "    )",
        "    (",
        f"        input  logic clk,",
        f"        input  logic rst_n,",
        f"        input  logic {_w(Bin)} sig_in,",
        f"        input  logic sig_in_valid,",
        f"        output logic {_w(Bout)} sig_out,",
        f"        output logic sig_out_valid",
        "    );",
        "",
    ]

    # -------------------------------------------------------------------------
    # Integrator section
    # -------------------------------------------------------------------------
    L += [
        "    //--------------------------------------------------------------------------",
        "    // Integrators (running at sig_in_valid rate)",
        "    //--------------------------------------------------------------------------",
    ]

    for i, st in enumerate(integ_stages):
        L.append(f"    logic signed {_w(st.width)} integ_{i};  // stage {st.index}, width={st.width}")
    L.append("")

    # Bipolar PDM mapping: sig_in=1 -> +1, sig_in=0 -> -1
    L += [
        f"    // PDM bipolar mapping: sig_in=1 -> +1, sig_in=0 -> -1",
        f"    localparam logic signed {_w(integ0_w)} PDM_PLUS_ONE = {integ0_w}'sd1;",
        f"    localparam logic signed {_w(integ0_w)} PDM_MINUS_ONE = -{integ0_w}'sd1;",
        "",
        f"    logic signed {_w(integ0_w)} sig_in_se;",
        "",
        f"    assign sig_in_se = sig_in ? PDM_PLUS_ONE : PDM_MINUS_ONE;",
        "",
    ]

    for i, st in enumerate(integ_stages):
        if i == 0:
            addend = "sig_in_se"
        else:
            prev_width = integ_stages[i - 1].width
            if prev_width > st.width:
                addend = f"integ_{i - 1}[{prev_width - 1}:{prev_width - st.width}]"
            else:
                addend = f"integ_{i - 1}"
        L += [
            f"    always_ff @(posedge clk or negedge rst_n)",
            f"        if (!rst_n)",
            f"            integ_{i} <= {st.width}'h0;",
            f"        else if (sig_in_valid)",
            f"            integ_{i} <= integ_{i} + {addend};",
            "",
        ]

    # -------------------------------------------------------------------------
    # Decimation counter — counts valid input samples, fires every R samples
    # -------------------------------------------------------------------------
    L += [
        "    //--------------------------------------------------------------------------",
        "    // Decimation counter — fires every R valid input samples",
        "    //--------------------------------------------------------------------------",
        f"    localparam logic {_w(cnt_bits)} DEC_MAX = {cnt_bits}'({R - 1});",
        f"    logic {_w(cnt_bits)} dec_cnt;",
        "    logic dec_en;",
        "",
        f"    always_comb dec_en = sig_in_valid && (dec_cnt == DEC_MAX);",
        "",
        "    always_ff @(posedge clk or negedge rst_n)",
        "        if (!rst_n)",
        f"            dec_cnt <= {cnt_bits}'h0;",
        "        else if (dec_en)",
        f"            dec_cnt <= {cnt_bits}'h0;",
        "        else if (sig_in_valid)",
        "            dec_cnt <= dec_cnt + 1'b1;",
        "",
    ]

    # -------------------------------------------------------------------------
    # Comb section — combinational path (PIPELINE_ENABLE == 0)
    # -------------------------------------------------------------------------
    # Each comb stage: delay register(s) of depth M + difference computation.
    # Feed-in to comb[0] is the last integrator output (truncated to comb[0].width).

    last_integ_w = integ_stages[-1].width

    # Declare delay regs and diff signals for all comb stages
    L += [
        "    //--------------------------------------------------------------------------",
        "    // Comb stages",
        "    //    PIPELINE_ENABLE=0: combinational differences, only delays registered",
        "    //    PIPELINE_ENABLE=1: all differences registered (lower fmax pressure)",
        "    //--------------------------------------------------------------------------",
    ]

    for i, st in enumerate(comb_stages):
        # M delay registers per comb stage
        for m in range(M):
            L.append(f"    logic signed {_w(st.width)} comb_{i}_dly_{m};  // comb stage {st.index}, delay tap {m}")
        L.append(f"    logic signed {_w(st.width)} comb_{i}_diff;  // comb stage {st.index} difference output")
    L.append("")

    # ---- Delay registers (always_ff, gated by dec_en) — common to both modes
    for i, st in enumerate(comb_stages):
        for m in range(M):
            if m == 0:
                if i == 0:
                    # Feed from last integrator; truncate if narrower
                    if last_integ_w > st.width:
                        feed = f"integ_{N - 1}[{last_integ_w - 1}:{last_integ_w - st.width}]"
                    else:
                        feed = f"integ_{N - 1}"
                else:
                    prev_comb_w = comb_stages[i - 1].width
                    if prev_comb_w > st.width:
                        feed = f"comb_{i - 1}_diff[{prev_comb_w - 1}:{prev_comb_w - st.width}]"
                    else:
                        feed = f"comb_{i - 1}_diff"
            else:
                feed = f"comb_{i}_dly_{m - 1}"
            L += [
                f"    always_ff @(posedge clk or negedge rst_n)",
                f"        if (!rst_n)",
                f"            comb_{i}_dly_{m} <= {st.width}'h0;",
                f"        else if (dec_en)",
                f"            comb_{i}_dly_{m} <= {feed};",
                "",
            ]

    # ---- Differences — generate block selects between combinational and registered
    def _comb_feed(i: int) -> str:
        """Signal feeding into comb stage i (before the delay subtraction)."""
        if i == 0:
            if last_integ_w > comb_stages[0].width:
                return f"integ_{N - 1}[{last_integ_w - 1}:{last_integ_w - comb_stages[0].width}]"
            return f"integ_{N - 1}"
        prev_comb_w = comb_stages[i - 1].width
        curr_comb_w = comb_stages[i].width
        if prev_comb_w > curr_comb_w:
            return f"comb_{i - 1}_diff[{prev_comb_w - 1}:{prev_comb_w - curr_comb_w}]"
        return f"comb_{i - 1}_diff"

    L += [
        "    generate",
        "        if (PIPELINE_ENABLE == 1'b0) begin : g_comb",
        "            // Combinational comb differences",
    ]
    for i in range(N):
        L.append(f"            always_comb comb_{i}_diff = {_comb_feed(i)} - comb_{i}_dly_{M - 1};")
    L += [
        "        end else begin : g_pipe",
        "            // Registered comb differences (PIPELINE_ENABLE=1)",
    ]
    for i, st in enumerate(comb_stages):
        feed = _comb_feed(i)
        L += [
            f"            always_ff @(posedge clk or negedge rst_n)",
            f"                if (!rst_n)",
            f"                    comb_{i}_diff <= {st.width}'h0;",
            f"                else if (dec_en)",
            f"                    comb_{i}_diff <= {feed} - comb_{i}_dly_{M - 1};",
        ]
    L += [
        "        end",
        "    endgenerate",
        "",
    ]

    # -------------------------------------------------------------------------
    # Output register and valid
    # -------------------------------------------------------------------------
    last_comb = f"comb_{N - 1}_diff"
    last_comb_w = comb_stages[-1].width

    L += [
        "    //--------------------------------------------------------------------------",
        "    // Output register — truncate final comb to Bout",
        "    //--------------------------------------------------------------------------",
        f"    always_ff @(posedge clk or negedge rst_n)",
        f"        if (!rst_n)",
        f"            sig_out <= {Bout}'h0;",
        f"        else if (dec_en)",
        f"            sig_out <= {last_comb}[{last_comb_w - 1}:{last_comb_w - Bout}];",
        "",
        "    //--------------------------------------------------------------------------",
        "    // Valid — single-cycle pulse when sig_out is updated",
        "    //--------------------------------------------------------------------------",
        "    always_ff @(posedge clk or negedge rst_n)",
        "        if (!rst_n)",
        "            sig_out_valid <= 1'b0;",
        "        else",
        "            sig_out_valid <= dec_en;",
        "",
        "endmodule : cic",
        "",
    ]

    return "\n".join(L)


